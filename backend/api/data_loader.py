# module1_traffic/run_module1.py writes annotated videos with OpenCV's
# cv2.VideoWriter using the "mp4v" fourcc, which encodes MPEG-4 Part 2
# ("mpeg4") video -- a codec no mainstream browser's <video> tag can decode
# natively (browsers need H.264/VP9/AV1). This is a playback/delivery
# problem only, not a pipeline defect: the pixel content (detection boxes,
# ROI overlay, labels) is untouched by Module 1's own logic and this backend
# never re-runs YOLO/ByteTrack. This transcodes a *copy* into H.264 the
# first time it's needed and caches it -- the original authoritative output
# file is never modified or overwritten.
MEDIA_CACHE_DIR = REPO_ROOT / "backend/media_cache"


def get_browser_playable_video(source: Path, cache_name: str) -> Path:
    """Return a browser-playable (H.264) copy of `source`, transcoding once
    via ffmpeg and caching it under MEDIA_CACHE_DIR if not already present."""
    MEDIA_CACHE_DIR.mkdir(parents=True, exist_ok=True)
    cached = MEDIA_CACHE_DIR / cache_name
    if cached.exists() and cached.stat().st_mtime >= source.stat().st_mtime:
        return cached
    if shutil.which("ffmpeg") is None:
        raise RuntimeError(
            "ffmpeg not found on PATH -- required to transcode the OpenCV-written "
            f"mpeg4 video at {source} into a browser-playable H.264 copy."
        )
    result = subprocess.run(
        [
            "ffmpeg", "-y", "-i", str(source),
            "-c:v", "libx264", "-preset", "fast", "-crf", "23",
            "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an",
            str(cached),
        ],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(f"ffmpeg transcode failed for {source}:\n{result.stderr[-2000:]}")
    return cached

