@lru_cache(maxsize=1)
def get_module1_dataset() -> pd.DataFrame:
    if not MODULE1_DATASET.exists():
        raise FileNotFoundError(f"Authoritative Module 1 dataset not found: {MODULE1_DATASET}")
    frame = pd.read_csv(MODULE1_DATASET)
    frame["vehicle_type"] = frame["vehicle_type"].astype(str).str.lower()
    return frame


@lru_cache(maxsize=1)
def get_vehicle_emissions() -> pd.DataFrame:
    if not VEHICLE_EMISSIONS.exists():
        raise FileNotFoundError(f"Authoritative vehicle_emissions.csv not found: {VEHICLE_EMISSIONS}")
    return pd.read_csv(VEHICLE_EMISSIONS)


@lru_cache(maxsize=1)
def get_manifest() -> pd.DataFrame:
    return pd.read_csv(MANIFEST)


@lru_cache(maxsize=1)
def get_model_metrics() -> dict:
    if not MODEL_METRICS.exists():
        raise FileNotFoundError(f"104-video model metrics not found: {MODEL_METRICS}")
    with MODEL_METRICS.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def classify_congestion(density) -> str:
    """Reuses the project's own traffic_condition() thresholds -- no new
    congestion definition is introduced by the frontend."""
    if density is None or pd.isna(density):
        return "N/A"
    return traffic_condition(float(density))


def dominant_class_per_track(frame: pd.DataFrame) -> pd.Series:
    """Majority vehicle_type per (video_id, vehicle_id) track -- the same
    class-flicker handling already used by copert_emission_engine.py and the
    windowed training-dataset builders, reused here rather than reinvented."""
    return (
        frame.groupby(["video_id", "vehicle_id"])["vehicle_type"]
        .agg(lambda values: values.mode().iat[0])
    )
